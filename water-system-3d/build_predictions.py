#!/usr/bin/env python3
"""Build foothills-predictions.json, the model predictions the 3D map draws
over the Foothills influent record.

Reads ../experiments/rolling/results/predictions-TOC.csv and
predictions-Alk.csv, written by `.venv/bin/python -m rolling.predict` from
experiments/. One trace per model (rf_grid, catboost) plus the actual series
the models were scored against. Nothing here touches the network.

    python3 build_predictions.py
"""

import csv
import json
import os
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(HERE, "..", "experiments", "rolling", "results")
OUT = os.path.join(HERE, "foothills-predictions.json")

TARGETS = {
    "toc": {"csv": "TOC", "unit": "mg/L", "threshold": 3, "threshold_side": "above"},
    "alk": {"csv": "Alk", "unit": "mg/L", "threshold": 60, "threshold_side": "below"},
}
MODELS = ("rf_grid", "catboost")
DECIMALS = 2

COMMENT = (
    "Per-day model predictions of TOC and alkalinity at the Foothills plant "
    "influent, from the rolling-origin evaluation (train on every year before "
    "N, test on year N), so each value is an out-of-sample prediction for that "
    "day. Generated by build_predictions.py from "
    "experiments/rolling/results/predictions-*.csv. Built on provisional "
    "Denver Water data; terms in data/TERMS.md."
)


def read_rows(target_csv):
    path = os.path.join(RESULTS_DIR, f"predictions-{target_csv}.csv")
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def series(rows, value_key):
    by_day = {row["date"]: round(float(row[value_key]), DECIMALS) for row in rows}
    return [{"t": day, "v": by_day[day]} for day in sorted(by_day)]


def model_series(rows, model):
    return series([row for row in rows if row["model"] == model], "predicted")


def build_target(rows, spec):
    return {
        "unit": spec["unit"],
        "threshold": spec["threshold"],
        "threshold_side": spec["threshold_side"],
        "models": {model: model_series(rows, model) for model in MODELS},
        "actual": series(rows, "actual"),
    }


def build():
    targets = {key: build_target(read_rows(spec["csv"]), spec) for key, spec in TARGETS.items()}
    return {"_comment": COMMENT, "generated": date.today().isoformat(), "targets": targets}


def main():
    predictions = build()
    with open(OUT, "w") as f:
        json.dump(predictions, f, separators=(",", ":"))
    for key, target in predictions["targets"].items():
        counts = {m: len(s) for m, s in target["models"].items()}
        print(f"{key}: {counts}, actual {len(target['actual'])}")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
